	<h1>Sources &amp; methodology</h1>

	<h2>Dedication</h2>
	<p class="dedication">
		This site began with my teacher, Do Tulku Rinpoche. A few years ago he suggested I read about
		Xuanzang’s journey to India. Following that road through the pilgrims’ own records became this
		attempt to let others walk it too, and see what they saw. It is dedicated to him, with
		gratitude.
	</p>

	<h2>The three records</h2>
	<ul>
		<li>
			<strong>Faxian</strong>, <em>A Record of Buddhistic Kingdoms</em> (c. 414 CE), translated by
			James Legge, Oxford, 1886. The earliest and shortest account: an overland journey out
			(399–404) and a sea voyage home via Ceylon and Java (409–414).
		</li>
		<li>
			<strong>Xuanzang</strong>, <em>The Great Tang Dynasty Record of the Western Regions</em>
			(646 CE), translated by Li Rongxi, BDK English Tripiṭaka, 1996. The most detailed: some 110
			“countries” in twelve fascicles, of which he visited most in person between 629 and 645.
		</li>
		<li>
			<strong>Yijing</strong>, <em>A Record of the Buddhist Religion as Practised in India and the
			Malay Archipelago</em> (c. 691 CE), translated by Junjirō Takakusu, Oxford, 1896. Not a
			travelogue but a treatise on monastic practice — and the best surviving witness to which
			schools flourished where.
		</li>
		<li>
			<strong>Yijing</strong> (supplementary), <em>Biography of Eminent Monks Who Went to the
			Western World in Search of the Law During the Great T'ang Dynasty</em> (Kao Seng Chuan,
			c. 691 CE), translated by Latika Lahiri, Delhi, 1986. Yijing’s memoirs of fifty-six fellow
			pilgrims, with his own detailed description of Nālandā — used to corroborate and refine a
			handful of his entries (each such fact carries its own quotation under “Also in the
			pilgrim’s writings”).
		</li>
	</ul>

	<h2>How the data was made</h2>
	<p>
		Every place on the map is one pilgrim’s recorded visit, extracted from the translations above
		with a mandatory verbatim quotation as provenance. Visits to the same real place were then
		reconciled, so that a single pin can carry up to three witnesses across three centuries.
		Nothing is invented: where the pilgrim does not name a school or count the monks, the data
		says so.
	</p>

	<h2>A note on “Hīnayāna”</h2>
	<p>
		The Victorian translations use “Hīnayāna” (“lesser vehicle”) where the pilgrims described
		monasteries of the early Buddhist schools. The term is pejorative and is not used on this
		site: we say <strong>Śrāvakayāna</strong> (“the vehicle of the hearers”) throughout. Likewise
		Yijing never wrote “Theravāda”; where the sources say <em>Sthavira</em>, the site shows
		“Sthavira (Theravāda)” as a scholarly bridge, not a quotation.
	</p>

	<h2>Locations and honesty</h2>
	<p>
		Coordinates come from the translators’ notes and established scholarly identifications (Legge’s
		footnotes, Cunningham’s <em>Ancient Geography of India</em>, and successors). Each pin carries
		a confidence level — <em>confident</em>, <em>probable</em>, or <em>approximate</em> — drawn on
		the map as a halo: the wider and blurrier the halo, the less certain the identification.
		Hollow markers are places the pilgrim only describes from report; the route lines never pass
		through them. The soft colour fields showing yāna dominance are deliberately borderless —
		sparse medieval testimony cannot justify hard edges.
	</p>

	<h2>Sarvāstivāda and Mūlasarvāstivāda</h2>
	<p>
		Xuanzang’s translator writes plain “Sarvāstivāda” throughout, but Yijing, who lived ten years
		under the rule he describes, distinguishes his <strong>Mūlasarvāstivāda</strong> from the
		older Daśādhyāya Sarvāstivāda, and warns (in effect) against relabelling wholesale. The map
		therefore adds the Mūlasarvāstivāda <em>site by site</em>, only where Yijing’s regional
		testimony supports it: the Sarvāstivāda monasteries of Magadha and Northern India, and Nālandā
		itself on his direct evidence. The Tarim oasis monasteries, which followed the older
		tradition, are deliberately left as the pilgrims recorded them. The pilgrims’ own words in
		each place’s detail panel are never altered.
	</p>

	<h2>Vajrayāna: a hidden lineage, read backwards</h2>
	<p>
		No pilgrim writes “Vajrayāna”. In their era it was an esoteric lineage transmitted orally
		inside Mahāyāna communities, and it became public only in the century after Yijing sailed
		home. But the records carry early traces of its mantra practice, and, exactly as with the
		Mūlasarvāstivāda above, the map reads the later evidence backwards <em>site by site</em>, at
		two places only, each shown as a flagged “(derived)” value alongside the witnessed yāna and
		never replacing it. On the map it is drawn the same way: the bubble keeps the witnessed
		colour, and the derived Vajrayāna appears as a purple ring around it.
	</p>
	<p>
		<strong>Udyāna</strong> (631 CE): Xuanzang found a Mahāyāna country whose people “take the
		recitation of spells as their profession” and whose monks are “specially adept in reciting
		incantations”. This is the Oḍḍiyāna that Vajrayāna tradition reveres as the homeland of
		Padmasambhava and a source of the tantras, and openly Vajrayāna rock sculpture appears in the
		Swat valley in the seventh–eighth centuries. <strong>Nālandā</strong> (670s): Yijing himself
		“regularly went to the altar” there and tried — unsuccessfully, he admits — to master the
		Vidyādhara-piṭaka, a corpus of mantras he says ran to 100,000 stanzas and could not be
		understood until expounded orally. Under the Pālas, a few decades later, Nālandā taught
		Vajrayāna openly, and its excavated bronzes include Vajrayāna deities.
	</p>
	<p>
		The ring, not a recolouring, is deliberate. A monastic community that takes up the mantra
		path does not stop being what it was: the monks still keep their vinaya — and every
		ordination lineage is a Śrāvakayāna inheritance, for the Mahāyāna never produced a vinaya of
		its own — while studying Mahāyāna literature and practising Vajrayāna meditation. A
		“Vajrayāna monastery” is therefore really <em>triyāna</em>, the three vehicles layered rather
		than exclusive; only outside the monastery could the mantra path be practised on its own.
		For the same reason, “Mahāyāna” on this map describes what a community studied and revered,
		not a separate institution. Yijing says as much: “Which of the four schools should be grouped
		with the Mahāyāna or with the Hīnayāna is not determined”, for “both adopt one and the same
		discipline (Vinaya)” — the Mahāyānists are simply “those who worship the Bodhisattvas and
		read the Mahāyāna Sūtras”. The “mixed” places, where both literatures were studied side by
		side, are the same layering seen from the other end. On the definitional problem see Jonathan
		A. Silk, “What, If Anything, Is Mahāyāna Buddhism? Problems of Definitions and
		Classifications”, <em>Numen</em> 49/4 (2002), pp. 355–405.
	</p>
	<p>
		The derivation is gated on the pilgrim’s own testimony: it applies only where the witnessed
		community is Mahāyāna, so Faxian’s Udyāna of 403 CE — a Śrāvakayāna country in his account —
		is left exactly as he recorded it. Dhānakaṭaka, despite Xuanzang’s story of Bhāvaviveka
		reciting the Vajrapāṇi-dhāraṇī there and the later Kālacakra tradition attached to the site,
		is deliberately excluded: the community he records is Mahāsāṃghika. References: Anna
		Filigenzi, <em>Art and Landscape: Buddhist Rock Sculptures of Late Antique Swat/Uḍḍiyāna</em>
		(Austrian Academy of Sciences, 2015); Giuseppe Tucci, “Travels of Tibetan Pilgrims in the
		Swat Valley” (1940), for the identification of Swat as Oḍḍiyāna; Chou Yi-liang, “Tantrism in
		China”, <em>Harvard Journal of Asiatic Studies</em> 8 (1945), on Yijing’s Vidyādhara-piṭaka
		notice; Ronald M. Davidson, <em>Indian Esoteric Buddhism</em> (Columbia, 2002), on the
		tradition’s emergence into the open.
	</p>

	<h2>What the data cannot say</h2>
	<p>
		About a third of recorded visits name no yāna at all — those places stay neutral on the map
		rather than being guessed. Xuanzang reports 26 countries at second hand. Three visits have no
		derivable year and are shown with estimated dates. Vajrayāna was only beginning to emerge in
		the pilgrims’ era and never appears under that name in their records — the two derived
		attributions above are the closest the sources allow.
	</p>
	<p>
		The pilgrims often count in phrases rather than figures — “several thousand monks”, “a few
		hundred”. Marker sizes on the map use documented representative values for such phrases
		(several myriads ≈ 10,000; several thousand ≈ 3,000; several hundred ≈ 500; few ≈ 20), but
		the detail panels always show the original wording.
	</p>
	<p>
		Two famous monasteries are conspicuously absent: <strong>Odantapurī</strong> and
		<strong>Vikramaśīla</strong> were founded under the Pāla dynasty in the eighth century — a
		generation or more after Yijing sailed home — so none of the three pilgrims could have seen
		them. Their absence from this map is itself a small piece of historical evidence.
	</p>

