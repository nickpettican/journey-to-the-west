const details = {};
for (const c of canonical) {
	details[c.canonicalId] = {
		canonical: c,
		visits: c.visitedBy
			.map((v) => entryById.get(v.placeId))
			.filter(Boolean)
			// The entry itself (the pilgrim's words) is never altered; the
			// derived yāna rides alongside, flagged, for the detail panel.
			.map((e) => {
				const yd = derivedYanas(e);
				return yd.length ? { ...e, yanaDerived: yd } : e;
			})
			.sort((a, b) => (a.date?.year ?? 0) - (b.date?.year ?? 0))
	};
}
write('details.json', details);

