/**
 * Data pipeline: reads the extracted pilgrim records in data/ and produces the
 * derived artefacts the site consumes, in static/data/ (gitignored, rebuilt on
 * every dev/build run).
 *
 * Outputs:
 *   static/data/pilgrims.json
 *   static/data/places-{faxian|xuanzang|yijing}.geojson
 *   static/data/routes.geojson           (firsthand stops only — hearsay places
 *                                         were reported, not visited, so the
 *                                         route line must not pass through them)
 *   static/data/regions.geojson          (fuzzy testimony zones from data/regions.source.json)
 *   static/data/observations.json        (Yijing's claims keyed to region ids)
 *   static/data/details.json             (canonicalId -> canonical record + full visits)
 *   static/data/journeys/{pilgrim}.json  (scrolly manuscripts)
 *   src/lib/data/labels.ts               (generated label/colour module)
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { estimateMonksFromText } from '../src/lib/data/monkEstimates.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(root, 'data');
const OUT = join(root, 'static', 'data');
mkdirSync(join(OUT, 'journeys'), { recursive: true });

const read = (p) => JSON.parse(readFileSync(join(DATA, p), 'utf8'));
const write = (p, v) => writeFileSync(join(OUT, p), JSON.stringify(v));

const pilgrims = read('pilgrims.json');
const labels = read('labels.json');
const canonical = read('canonical/places.json');
const observationsRaw = read('yijing/observations.json');
const regionsSource = read('regions.source.json');
const sources = {
	faxian: read('faxian/places.json'),
	xuanzang: read('xuanzang/places.json'),
	yijing: read('yijing/places.json')
};

/* ---------------------------------------------------------------- labels --- */

// places.json stores yana WITH diacritics; sect as ASCII keys. Normalise both
// directions via the labels file.
const yanaDisplayToKey = Object.fromEntries(
	Object.entries(labels.yana).map(([key, display]) => [display, key])
);
const toYanaKey = (v) => yanaDisplayToKey[v] ?? (labels.yana[v] ? v : 'unknown');

// Colours live in src/lib/data/colours.ts (hand-owned, NEVER generated) —
// this script only generates labels and names.
